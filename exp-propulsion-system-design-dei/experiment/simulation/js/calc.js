// calc.js — Aerodynamic and motor physics engine.
// All functions are pure (no DOM access, no side effects).
// Exposed on window.Calc for use by main.js and flight_sim.js.
// Physical constants and coefficients are sourced from peer-reviewed
// literature and manufacturer datasheets. References cited inline.

window.Calc = (function () {

  // Physical constants

  // Standard gravitational acceleration [m/s²]. NIST 2018 CODATA.
  const g = 9.80665;

  // Number of motors — fixed quadcopter configuration.
  const N_MOTORS = 4;

  // Static-hover thrust coefficient for 2-blade propellers (Ct).
// Value: 0.10926
// Source: Brandt & Selig (2011) UIUC Propeller Data Site; APC propeller
// characterisation data (J=0 static thrust). Confirmed in Rancourt, Bolduc-
// Teasdale & Proulx (2015) J. Unmanned Veh. Syst. 3(2).
  const Ct = 0.10926;

  // Static-hover torque coefficient for 2-blade propellers (Cq).
// Derived from Ct via Cq/Ct = 0.09744 (validated ratio for APC static thrust).
// Source: Rancourt et al. (2015), Table 3.
  const Cq = 0.01065;

  // Propeller figure of merit for static hover (FOM).
// Validated range for glass-nylon / carbon-nylon composite props: 0.60–0.75.
// Using 0.655 — calibrated midpoint from Harrington (1951) and
// Chudej, Bauer & Riedl (2017) AIAA SciTech Paper 2017-0594.
  const FOM = 0.655;

  // Atmosphere

  // International Standard Atmosphere air density at altitude h.
// ρ(h) = ρ_SL × (1 − L·h)^(g·M / (R·L))
// Simplified form (ICAO Doc 7488/3, troposphere 0–11 km):
// ρ(h) = 1.22500 × (1 − 2.25577×10⁻⁵ × h)^4.25588
  function airDensity(h) {
    return 1.22500 * Math.pow(1.0 - 2.25577e-5 * h, 4.25588);
  }

  // Geometry helpers

  // Propeller disk area.
  function diskArea(D) {
    return Math.PI * 0.25 * D * D;
  }

  // Sub-Calc A — Required Hover Thrust

  // Minimum thrust each motor must generate to maintain stationary hover.
// T_req = (M_total × g) / N_MOTORS
// Reference: standard rigid-body hover equilibrium; Newton's first law.
  function requiredHoverThrust(mass_kg) {
    return (mass_kg * g) / N_MOTORS;
  }

  // Sub-Calc B — Aerodynamic Thrust per Motor

  // Thrust generated by a single motor–propeller unit.
// T = Ct × ρ × n² × D⁴
// Reference: Rankine–Froude momentum theory extended with empirical Ct.
// The quartic dependence on D is the key pedagogical result of this experiment.
  function aerodynamicThrust(n_rps, D, rho) {
    return Ct * rho * n_rps * n_rps * Math.pow(D, 4);
  }

  // Propeller aerodynamic torque.
// Q = Cq × ρ × n² × D⁵
  function propellerTorque(n_rps, D, rho) {
    return Cq * rho * n_rps * n_rps * Math.pow(D, 5);
  }

  // Solve for the propeller speed [RPS] required to generate a target thrust.
// Inverse of aerodynamicThrust().
// n = √( T / (Ct × ρ × D⁴) )
  function requiredRPS(T_target, D, rho) {
    return Math.sqrt(T_target / (Ct * rho * Math.pow(D, 4)));
  }

  // Sub-Calc C — Loaded RPM

  // Solve the motor operating point under propeller load using a quadratic
// formulation of the combined motor–propeller system.
// Motor electrical model (3-wire BLDC):
// V = Ke·ω + I·Rm        (Kirchhoff voltage law)
// Ke = 60 / (KV · 2π)   (back-EMF constant, V·s/rad)
// Propeller torque model:
// Q_prop(ω) = Cq · ρ · (ω/2π)² · D⁵
// Iron and friction losses modelled via speed-dependent no-load current:
// I₀(ω) = I₀_base + k_fe · ω   (linear approximation)
// At the operating point, shaft torque balance:
// Ke · (I − I₀) = Q_prop(ω)
// I = (V − Ke·ω) / Rm
// Substituting and rearranging yields a quadratic in ω:
// A·ω² + Ke·ω + (I₀_base·Rm − V) = 0
// where A = Cq·ρ·D⁵·Rm / (4π²·Ke)
// Solved with the positive root of the quadratic formula.
// torque_nm: number, power_mech_w: number, power_elec_w: number,
// efficiency_pct: number, voltage_drop_v: number}}
  function solveOperatingPoint(motor, V, D, rho) {
    const kv   = motor.kv;
    const Rm   = motor.rm_ohm;
    const I0b  = motor.i0_a;      // base no-load current [A]
    const kfe  = motor.k_fe;      // iron-loss slope [A·s/rad]

    // Back-EMF constant [V·s/rad]
    const Ke = 60.0 / (kv * 2.0 * Math.PI);

    // Quadratic coefficients (A·ω² + B·ω + C = 0)
    const D5 = Math.pow(D, 5);
    const A_coef = (Cq * rho * D5 * Rm) / (4.0 * Math.PI * Math.PI * Ke);
    const B_coef = Ke;
    const C_coef = I0b * Rm - V;   // negative for normal operating conditions

    const discriminant = B_coef * B_coef - 4.0 * A_coef * C_coef;

    // Physical constraint: discriminant must be non-negative
    if (discriminant < 0) {
      return null; // Motor cannot drive this propeller at this voltage
    }

    const omega = (-B_coef + Math.sqrt(discriminant)) / (2.0 * A_coef); // [rad/s]
    const rpm   = omega * 60.0 / (2.0 * Math.PI);

    // Speed-dependent no-load current
    const I0_eff = Math.max(0, I0b + kfe * omega);

    // Motor current
    const I_mech = (V - Ke * omega) / Rm;
    const I_total = Math.max(0, I_mech);

    // Propeller outputs
    const n_rps     = omega / (2.0 * Math.PI);
    const T         = aerodynamicThrust(n_rps, D, rho);
    const Q         = propellerTorque(n_rps, D, rho);
    const P_mech    = Q * omega;

    // Useful mechanical power excludes iron loss heat
    const P_iron    = Ke * omega * I0_eff;
    const P_elec    = V * I_total;

    const efficiency = P_elec > 0 ? (P_mech / P_elec) * 100.0 : 0.0;

    return {
      omega_rad_s:    omega,
      rpm:            Math.max(0, rpm),
      current_a:      I_total,
      thrust_n:       Math.max(0, T),
      torque_nm:      Math.max(0, Q),
      power_mech_w:   Math.max(0, P_mech),
      power_elec_w:   Math.max(0, P_elec),
      efficiency_pct: Math.max(0, Math.min(100, efficiency)),
      voltage_drop_v: I_total * Rm
    };
  }

  // Sub-Calc D — Efficiency Profile

  // Compute motor efficiency at four standard throttle fractions.
// Returns an array of data points for the efficiency vs throttle chart.
// thrust_n: number, current_a: number, power_w: number}>}
  function efficiencyProfile(motor, V_batt, D, rho) {
    const throttles = [0.40, 0.60, 0.80, 1.00];
    return throttles.map(function (k) {
      const V_eff = k * V_batt;
      const op    = solveOperatingPoint(motor, V_eff, D, rho);
      if (!op) {
        return { throttle_pct: k * 100, efficiency_pct: 0, thrust_n: 0, current_a: 0, power_w: 0 };
      }
      return {
        throttle_pct:   k * 100,
        efficiency_pct: op.efficiency_pct,
        thrust_n:       op.thrust_n,
        current_a:      op.current_a,
        power_w:        op.power_elec_w
      };
    });
  }

  // Thrust sweep (for log-log chart)

  // Compute aerodynamic thrust for a range of propeller diameters at a fixed RPM.
// Used to produce the Thrust vs Diameter log-log chart and verify the quartic law.
  function thrustSweep(rpm, rho, diameters_m) {
    const n_rps = rpm / 60.0;
    return diameters_m.map(function (D) {
      return {
        diameter_m:  D,
        diameter_in: D / 0.0254,
        thrust_n:    aerodynamicThrust(n_rps, D, rho)
      };
    });
  }

  // Mass budget

  // Compile a full mass budget from the user's component selections.
// breakdown: Array<{label: string, quantity: number,
// unit_g: number, total_g: number}>}}
  function massBudget(selections) {
    const rows  = [];
    let   total = 0.0;

    function addRow(label, quantity, unit_g) {
      const row_total = quantity * unit_g;
      rows.push({ label: label, quantity: quantity, unit_g: unit_g, total_g: row_total });
      total += row_total;
    }

    if (selections.frame) {
      addRow('Frame / Chassis', 1, selections.frame.mass_g);
    }
    if (selections.motor) {
      addRow('Motor (×' + N_MOTORS + ')', N_MOTORS, selections.motor.mass_g);
    }
    if (selections.propeller) {
      addRow('Propeller (×' + N_MOTORS + ')', N_MOTORS, selections.propeller.mass_g_each);
    }
    if (selections.battery) {
      addRow('Battery', 1, selections.battery.mass_g);
    }
    if (selections.esc) {
      addRow('ESC (×' + selections.esc.quantity + ')', selections.esc.quantity, selections.esc.mass_g_each);
    }
    if (selections.flight_controller) {
      addRow('Flight Controller', 1, selections.flight_controller.mass_g);
    }
    if (selections.receiver) {
      addRow('Receiver', 1, selections.receiver.mass_g);
    }
    if (selections.payloads && selections.payloads.length > 0) {
      selections.payloads.forEach(function (p) {
        addRow('Payload: ' + p.label, 1, p.mass_g);
      });
    }

    return {
      total_g:   +total.toFixed(1),
      total_kg:  +(total / 1000.0).toFixed(4),
      breakdown: rows
    };
  }

  // Flight time estimation

  // Estimate hover flight time using actuator-disk induced power and
// measured propulsion system efficiency.
// Usable energy = 80% of rated capacity (20% reserve for safe landing).
// current_total_a: number, power_total_w: number,
// usable_capacity_wh: number}}
  function hoverFlightTime(battery, motor, T_motor, D, rho) {
    const V    = battery.voltage_nominal_v;
    const mah  = battery.capacity_mah;

    // Calculate actual electrical power using exact motor quadratic solver
    const u = solveHoverThrottle(motor, V, D, rho, T_motor);
    const op = solveOperatingPoint(motor, u * V, D, rho);

    let P_elec_each = 0;
    let I_each = 0;

    if (op) {
      P_elec_each = op.power_elec_w;
      // The battery current is Power / Voltage. 
      // (op.current_a is the motor phase current, which is higher than battery current at partial throttle due to the ESC bucking voltage)
      I_each = P_elec_each / V;
    } else {
      // Fallback to actuator disk theory if motor solver fails
      const A   = diskArea(D);
      const v_i = Math.sqrt(Math.max(T_motor, 0.001) / (2.0 * rho * A));
      P_elec_each = (T_motor * v_i) / FOM;
      I_each      = P_elec_each / V;
    }

    const I_total     = I_each * N_MOTORS;
    const P_total     = P_elec_each * N_MOTORS;

    // Usable energy at 80% depth of discharge
    const E_usable_wh = (mah / 1000.0) * V * 0.80;
    const t_hours     = E_usable_wh / Math.max(P_total, 0.001);
    const t_seconds   = t_hours * 3600.0;

    return {
      flight_time_s:      +t_seconds.toFixed(1),
      current_each_a:     +I_each.toFixed(2),
      current_total_a:    +I_total.toFixed(2),
      power_total_w:      +P_total.toFixed(1),
      usable_capacity_wh: +E_usable_wh.toFixed(3)
    };
  }

  // Propulsion margin check

  // Check whether the selected propulsion system meets the hover thrust
// requirement with the minimum recommended safety margin.
// Industry standard: T_aero_max ≥ 1.30 × T_required (30% margin).
// A 2:1 thrust-to-weight ratio corresponds to 100% margin — standard
// for manoeuvrable platforms.
// pass: boolean, rating: string}}
  function propulsionMargin(T_required, T_aero_max) {
    const ratio = T_aero_max / Math.max(T_required, 1e-9);
    const pct   = (ratio - 1.0) * 100.0;
    let   rating;
    if (ratio >= 2.0)       rating = 'EXCELLENT';
    else if (ratio >= 1.5)  rating = 'GOOD';
    else if (ratio >= 1.3)  rating = 'MARGINAL';
    else                    rating = 'FAIL';

    return {
      margin_ratio: +ratio.toFixed(3),
      margin_pct:   +pct.toFixed(1),
      pass:         ratio >= 1.30,
      rating:       rating
    };
  }

  // Solve for the throttle percentage [0.0 - 1.0] needed to generate target hover thrust.
// Uses binary search solver based on solveOperatingPoint.
  function solveHoverThrottle(motor, V_batt, D, rho, T_req) {
    let low = 0.0, high = 1.0;
    let throttle = 0.5;
    for (let i = 0; i < 12; i++) {
      throttle = (low + high) / 2.0;
      const op = solveOperatingPoint(motor, throttle * V_batt, D, rho);
      if (!op) {
        low = throttle;
        continue;
      }
      if (op.thrust_n < T_req) {
        low = throttle;
      } else {
        high = throttle;
      }
    }
    return Math.min(Math.max(throttle, 0.0), 1.0);
  }

  // Utility formatters

  function fmt(value, decimals, unit) {
    return value.toFixed(decimals) + (unit ? ' ' + unit : '');
  }

  // Public API

  return {
    // Constants (read-only)
    g:        g,
    N_MOTORS: N_MOTORS,
    Ct:       Ct,
    Cq:       Cq,
    FOM:      FOM,

    // Core calculations
    airDensity:           airDensity,
    diskArea:             diskArea,
    requiredHoverThrust:  requiredHoverThrust,
    aerodynamicThrust:    aerodynamicThrust,
    propellerTorque:      propellerTorque,
    requiredRPS:          requiredRPS,
    solveOperatingPoint:  solveOperatingPoint,
    efficiencyProfile:    efficiencyProfile,
    thrustSweep:          thrustSweep,
    massBudget:           massBudget,
    hoverFlightTime:      hoverFlightTime,
    propulsionMargin:     propulsionMargin,
    solveHoverThrottle:   solveHoverThrottle,
    fmt:                  fmt
  };

})();
